def seed():
    """Insert the question bank into the DB (idempotent).

    Topics are upserted by slug; questions are only added when a question
    with the same (topic, title) does not already exist, so re-running is
    safe and never duplicates rows.
    """
    app = create_app()
    with app.app_context():
        db.create_all()
        topic_map = {}
        for name, slug, order in TOPICS:
            topic = DSATopic.query.filter_by(slug=slug).first()
            if not topic:
                topic = DSATopic(name=name, slug=slug, icon="📘",
                                 description=f"{name} coding drills.",
                                 order=order)
                db.session.add(topic)
                db.session.flush()
            topic_map[slug] = topic
        db.session.commit()

        added = skipped = 0
        for item in BANK:
            topic = topic_map[item["topic"]]
            exists = DSAQuestion.query.filter_by(topic_id=topic.id,
                                                 title=item["title"]).first()
            if exists:
                skipped += 1
                continue
            db.session.add(DSAQuestion(
                topic_id=topic.id,
                title=item["title"],
                difficulty=item["difficulty"],
                description=item["description"],
                examples=item["tests"],
                starter_code=item["starter"],
                solution_code=item["solution"],
                test_cases=item["tests"],
                time_limit_ms=2000,
            ))
            added += 1
        db.session.commit()
        print(f"[seed_coding_lab] topics={len(topic_map)} "
              f"added={added} skipped={skipped}")


if __name__ == "__main__":
    seed()

